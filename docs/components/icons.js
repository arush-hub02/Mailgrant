/**
 * Render an SVG icon by name
 * @param {string} name
 * @param {string} [extraClass='']
 * @param {object} [attrs={}]
 * @returns {string}
 */
export function icon(name, extraClass = '', attrs = {}) {
  const content = iconPaths[name] || iconPaths.shield;
  const cls = extraClass ? `class="icon ${extraClass}"` : `class="icon"`;
  const attrStr = Object.entries(attrs).map(([k, v]) => ` ${k}="${String(v).replace(/"/g, '&quot;')}"`).join('');
  return `<svg ${cls} viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"${attrStr}>${content}</svg>`;
}
